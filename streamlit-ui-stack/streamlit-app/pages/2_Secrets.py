# pages/2_Secrets.py — BACKLOG #94 Phase 3, read-only MVP.
#
# Operator-facing view of the Infisical vault. The Streamlit page IS
# the only surface the operator ever touches; the Infisical UI itself
# is bound to 127.0.0.1:8090 and loopback-only (see infisical-stack/
# docker-compose.yml + bootstrap.sh deploy_infisical_stack()), so a
# customer-network browser can never reach it.
#
# Read-only. NO write/update/delete/rotate UI in this phase — that's
# Phase 6 (operator CRUD). NO scope-policy UI — that's Phase 4. NO
# MCP wiring — that's Phase 5. This page is intentionally the smallest
# viable reader so each later phase lands as an additive PR.
#
# Auth: require_auth() (auth.py). Streamlit admin login is NOT used to
# talk to Infisical — the operator token (INFISICAL_OPERATOR_TOKEN) is
# a separate machine-identity scoped to /adminlm/* with read-only
# grants. Generated by bootstrap.sh deploy_infisical_stack() once,
# persisted to ~/.hermes/secrets/infisical-operator.env (chmod 600).
#
# Audit: every secret view emits a streamlit_secret_view event to Loki
# (BACKLOG #77 pattern — log_event in loki_logger.py). The SECRET VALUE
# is NEVER included in the event payload — only metadata (key, path,
# user, timestamp). Logging the value would defeat the audit purpose
# and create a Loki-side plaintext dump of customer IT secrets.

