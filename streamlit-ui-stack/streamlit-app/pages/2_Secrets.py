def _list_secrets(path: str) -> list[dict]:
    """List secret METADATA under `path`. Never returns values.

    Endpoint: GET /api/v4/secrets?projectId=...&environment=...&secretPath=...&recursive=true
    Returns: list of {id, secretKey, secretPath, secretComment, createdAt, updatedAt, ...}
    Raises httpx.HTTPError on transport failure (caught below).

    NOTE: The deprecated /api/v3/secrets LIST endpoint returns {"secrets": []}
    in Infisical v0.166.2 even when secrets exist (verified on .220 2026-10-27).
    The v3 raw GET (used by _read_secret for single-secret reads) still works.
    The v4 LIST endpoint is the supported replacement and returns full
    metadata including secretComment, which the table uses for the
    Description column.
    """
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    params = {
        "projectId": pid,
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path,
        # recursive=true: include secrets in nested folders under this path.
        # v1.0 keeps secrets FLAT under /adminlm/it-systems/ but recursive
        # stays on so the page is forward-compatible if a customer adds
        # nested folders later. Phase 6 (operator CRUD) writes to this
        # path; the operator token is scoped to /adminlm/* read-only.
        "recursive": "true",
    }
    url = f"{base}/api/v4/secrets?{urlencode(params)}"
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    body = resp.json()
    # v4 returns {"secrets": [...], "imports": [...]}; we only want secrets.
    if isinstance(body, dict):
        return body.get("secrets") or body.get("data") or []
    if isinstance(body, list):
        return body
    return []


# NOTE: _list_subfolders() was removed in Phase 3.5 (2026-10-27). v1.0 keeps
# secrets FLAT under /adminlm/it-systems/ so there's no folder hierarchy to
# enumerate; the search bar replaces the previous folder-tree dropdown.

def _read_secret(path: str, secret_key: str) -> dict:
    """Fetch a single secret including its VALUE for the reveal pane.

    Endpoint: GET /api/v3/secrets/raw?workspaceId=...&environment=...&secretPath=...&secretKey=...
    Returns: dict with at least {secretKey, secretValue, secretPath, ...}
    """
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    params = {
        "workspaceId": pid,
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path,
        "secretKey": secret_key,
    }
    url = f"{base}/api/v3/secrets/raw?{urlencode(params)}"
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    return resp.json()


# ---------------------------------------------------------------------------
# Phase 6 (BACKLOG #95) — operator CRUD API helpers
# ---------------------------------------------------------------------------
#
# Writes use INFISICAL_ADMIN_TOKEN (the bootstrap-time root admin JWT), NOT
# the operator token. The operator token has the project `viewer` role for
# reads; writes require admin scope (mirrors Phase 4's pattern for managing
# machine-identity tokens on this same page).
#
# Endpoint shape verified against Infisical v0.166.2:
#   POST   /api/v4/secrets/{key}   body: {projectId, environment,
#                                     secretPath, secretValue, secretComment?, type?}
#   PATCH  /api/v4/secrets/{key}   body: {projectId, environment,
#                                     secretPath?, secretValue?, secretReminderNote?, type?}
#   DELETE /api/v4/secrets/{key}   body: {projectId, environment,
#                                     secretPath, type?}
# All three use `projectId` (not `workspaceId` as the v3 deprecation note
# suggests) — `workspaceId` in v3 was renamed to `projectId` in v4.
# `secretPath` has a `removeTrailingSlash` transform on the server side, so
# we pass it without the trailing "/" (e.g. "/adminlm/it-systems" not
# "/adminlm/it-systems/"). `type` defaults to "shared" on the server.

def _create_secret(path: str, key: str, value: str,
                   comment: str = "") -> dict:
    """Create a new secret at `path`. Operator-only (uses admin token).

    Returns: the response JSON from Infisical on success.
    Raises httpx.HTTPError on transport / status failure (caught by UI).
    """
    base = _infisical_url().rstrip("/")
    url = f"{base}/api/v4/secrets/{quote(key, safe='')}"
    body = {
        "projectId": _project_id(),
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path.rstrip("/"),
        "secretValue": value,
        "type": "shared",
    }
    if comment:
        body["secretComment"] = comment
    resp = httpx.post(
        url,
        json=body,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        timeout=_API_TIMEOUT_S,
    )
    resp.raise_for_status()
    return resp.json()


def _update_secret(path: str, key: str, value: str,
                   comment: str | None = None) -> dict:
    """Update an existing secret at `path`. Operator-only (uses admin token).

    PATCH supports partial updates — both `secretValue` and
    `secretComment` are optional. We send both here so the operator's
    description and value stay in sync (matches the "operator drives the
    value + meaning" intent from BACKLOG #94).

    `comment=None` means "don't change it"; empty string clears it.
    To clear the description explicitly, the UI should pass `comment=""`.
    """
    base = _infisical_url().rstrip("/")
    url = f"{base}/api/v4/secrets/{quote(key, safe='')}"
    body: dict = {
        "projectId": _project_id(),
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path.rstrip("/"),
        "secretValue": value,
        "type": "shared",
    }
    if comment is not None:
        # PATCH /api/v4/secrets/{key} accepts `secretComment` (the
        # description field). Verified on v0.166.2 — the handler reads
        # `secretComment: req.body.secretComment` and passes it to
        # `updateSecretRaw`. The schema also accepts `secretReminderNote`
        # but that's a separate field (cadence/reminder feature), NOT
        # the human description. Earlier versions of this helper sent
        # `secretReminderNote` and the comment silently didn't update
        # — fixed 2026-10-28.
        body["secretComment"] = comment
    resp = httpx.patch(
        url,
        json=body,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        timeout=_API_TIMEOUT_S,
    )
    resp.raise_for_status()
    return resp.json()


def _delete_secret(path: str, key: str) -> None:
    """Soft-delete a secret at `path`. Operator-only (uses admin token).

    Infisical's DELETE is a soft-delete — the secret is hidden but retained
    for audit (BACKLOG #94: "Delete uses Infisical's soft-delete (retains
    for audit)"). Page reloads via list_paths() will not show it.
    """
    base = _infisical_url().rstrip("/")
    url = f"{base}/api/v4/secrets/{quote(key, safe='')}"
    body = {
        "projectId": _project_id(),
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path.rstrip("/"),
        "type": "shared",
    }
    resp = httpx.request(
        "DELETE",
        url,
        json=body,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        timeout=_API_TIMEOUT_S,
    )
    # 404 on already-deleted is fine — operator-initiated delete is
    # idempotent in spirit.
    if resp.status_code not in (200, 202, 204, 404):
        resp.raise_for_status()


# ---------------------------------------------------------------------------
# Audit helper — operator secret CRUD (BACKLOG #77 loki_logger pattern)
# ---------------------------------------------------------------------------
#
# Mirrors `_audit_token` for machine-identity actions. Emits one NDJSON line
# to ~/.hermes/logs/streamlit/*.log per create/update/delete. Loki label
# {job="streamlit", source="adminlm_host"} matches the dashboard tile.
# Audit fields: {event, user_id, username, secret_key, secret_path, ts};
# NEVER includes the secret VALUE.

def _audit_secret(action: str, secret_key: str, secret_path: str) -> None:
    """Emit a streamlit_secret_{action} event to Loki. NEVER the secret value.

    `action` is one of: 'create', 'update', 'delete'. Failures swallowed
    so a Loki outage never blocks the operator's UX (same pattern as
    _audit_view and _audit_token on this page).
    """
    try:
        from loki_logger import log_event
        log_event("streamlit", {
            "event": f"streamlit_secret_{action}",
            "user_id": st.session_state.get("user_id"),
            "username": st.session_state.get("user"),
            "secret_key": secret_key,
            "secret_path": secret_path,
            # ts is added by log_event itself (RFC3339Nano); don't duplicate.
        })
    except Exception:
        pass  # logging failures must never block a successful op


# ---------------------------------------------------------------------------
# Machine-identity API helpers (Phase 4 — operator scope-policy UI)
# ---------------------------------------------------------------------------
#
# Infisical v0.166.2 machine-identity endpoints used here (verified against
# the pinned source tree — there is NO /api/v1/auth/machine-identities or
# /api/v1/project-machine-identities path in this version):
#
#   GET    /api/v1/projects/{projectId}/identities
#          → list project-scoped identities → {identities: [...], totalCount}
#   POST   /api/v1/projects/{projectId}/identities
#          body: {"name": "...", "roles": [{"role": "viewer", "isTemporary": false}]}
#          → create identity WITH project role in one call → {identity: {id}}
#   POST   /api/v1/auth/universal-auth/identities/{id}
#          (no body) → enable universal-auth on the identity
#   POST   /api/v1/auth/universal-auth/identities/{id}/client-secrets
#          body: {"description": "...", "numUsesLimit": 0, "ttl": 0}
#          → {clientSecret, clientSecretData: {...}}  (clientSecret value here)
#   GET    /api/v1/auth/universal-auth/identities/{id}
#          → {identityUniversalAuth: {id, clientId, ...}}  (login clientId here)
#   POST   /api/v1/auth/universal-auth/login
#          body: {"clientId": "...", "clientSecret": "..."}
#          → {accessToken, tokenType, expiresIn}
#   DELETE /api/v1/identities/{id}
#          → delete identity (cascades: revokes all credentials)
#
# Auth for reads: operator token (viewer role is sufficient for listing).
# Auth for writes (create/rotate/revoke): bootstrap-time admin token
# (INFISICAL_ADMIN_TOKEN) — the runtime operator token has viewer role
# only and cannot manage identities. Bootstrap.sh deploy_infisical_stack()
# generates and persists this admin token to the operator env file.

# Role granted to every agent machine identity. "viewer" = read-only at
# project level. v1.x enhancement (not in v1.0): folder-scoped grants via
# custom roles + permission filters (Infisical v0.166.2 lacks a stable API
# for this). Documented as a known limitation in the header comment.
AGENT_ROLE = "viewer"


def _list_machine_identities() -> list[dict]:
    """Return all machine identities in the project (incl. the operator's).

    Caller filters out the operator identity by name. Returns the raw API
    response list; we don't shape the data here so the caller can pick
    whichever fields it needs for display.
    """
    base = _infisical_url().rstrip("/")
    # v0.166.2: GET /api/v1/projects/{projectId}/identities → {identities, totalCount}
    # Project-scoped (no orgId needed; lists identities created in this project
    # via POST /api/v1/projects/{projectId}/identities).
    pid = _project_id()
    url = f"{base}/api/v1/projects/{pid}/identities"
    # Read uses operator token — viewer role is sufficient for listing identities.
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    body = resp.json()
    if isinstance(body, dict):
        # v0.166.2 shape: {"identities": [...], "totalCount": N} or {"data": [...]}.
        for key in ("identities", "data"):
            if key in body:
                return body[key] or []
        return []
    if isinstance(body, list):
        return body
    return []


def _create_machine_identity(name: str, description: str) -> str:
    """Create a machine identity. Returns the new id (empty string on failure)."""
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    # v0.166.2: POST /api/v1/projects/{projectId}/identities → {identity: {id}}
    # body: {name, roles:[{role, isTemporary}]} — creates identity AND grants
    # project role in one call (createProjectMachineIdentity).
    url = f"{base}/api/v1/projects/{pid}/identities"
    payload = {
        "name": name,
        "roles": [{"role": AGENT_ROLE, "isTemporary": False}],
    }
    resp = httpx.post(
        url,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        json=payload,
        timeout=_API_TIMEOUT_S,
    )
    resp.raise_for_status()
    body = resp.json()
    # v0.166.2 wraps in {"identity": {...}}.
    mi = body.get("identity") if isinstance(body, dict) else None
    if isinstance(mi, dict):
        return mi.get("id") or ""
    # Fall back to a flat shape (some builds return the identity directly).
    if isinstance(body, dict) and body.get("id"):
        return body["id"]
    return ""


def _add_universal_auth(mi_id: str) -> tuple[str, str]:
    """Add a universal-auth client to the machine identity.

    Returns (client_id, client_secret). Empty strings on failure.
    One-time per identity creation; rotate = call this again (replaces).

    v0.166.2 wiring:
      - POST /api/v1/auth/universal-auth/identities/{id}/client-secrets
        returns {clientSecret, clientSecretData: {...}}. The clientSecret
        value goes straight into the login body.
      - GET  /api/v1/auth/universal-auth/identities/{id}
        returns {identityUniversalAuth: {clientId, id, identityId, ...}}.
        The clientId (a server-generated UUID stored on the
        identity_universal_auths.clientId column) is what login's
        identityUaDAL.findOne({clientId}) actually looks up.
        The client-secrets response does NOT contain it (its .id and
        .identityUAId are PKs of OTHER tables).
    """
    base = _infisical_url().rstrip("/")

    # 1) Create the client secret. Capture the value (not the clientId).
    cs_url = f"{base}/api/v1/auth/universal-auth/identities/{mi_id}/client-secrets"
    cs_payload = {"description": "AdminLM agent client secret", "numUsesLimit": 0, "ttl": 0}
    cs_resp = httpx.post(
        cs_url,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        json=cs_payload,
        timeout=_API_TIMEOUT_S,
    )
    cs_resp.raise_for_status()
    cs_body = cs_resp.json()
    client_secret = (cs_body or {}).get("clientSecret", "")

    # 2) Fetch the identityUA's clientId (the login clientId). This MUST
    # come from the GET response, not from the POST response.
    ua_url = f"{base}/api/v1/auth/universal-auth/identities/{mi_id}"
    ua_resp = httpx.get(ua_url, headers=_admin_headers(), timeout=_API_TIMEOUT_S)
    ua_resp.raise_for_status()
    ua_body = ua_resp.json()
    client_id = ""
    if isinstance(ua_body, dict):
        iua = ua_body.get("identityUniversalAuth") or {}
        if isinstance(iua, dict):
            client_id = iua.get("clientId", "") or ""

    return client_id, client_secret


def _exchange_for_token(mi_id: str, client_id: str, client_secret: str) -> str:
    """Exchange client_id+secret for an access_token. Returns "" on failure."""
    base = _infisical_url().rstrip("/")
    # v0.166.2: POST /api/v1/auth/universal-auth/login → {accessToken, tokenType, expiresIn}
    # Note: the login endpoint is NOT identity-scoped — the clientId in the
    # body identifies the client secret, not the identity.
    url = f"{base}/api/v1/auth/universal-auth/login"
    payload = {"clientId": client_id, "clientSecret": client_secret}
    resp = httpx.post(
        url,
        headers={**_admin_headers(), "Content-Type": "application/json"},
        json=payload,
        timeout=_API_TIMEOUT_S,
    )
    resp.raise_for_status()
    body = resp.json()
    if isinstance(body, dict):
        return body.get("accessToken") or ""
    return ""


def _grant_role(mi_id: str, role: str = AGENT_ROLE) -> bool:
    """No-op in v0.166.2: project-scoped identities are created WITH the role.

    v0.166.2 POST /api/v1/projects/{projectId}/identities (createProjectMachineIdentity)
    creates the identity AND grants the project role in one call. There is no
    separate "grant role to existing identity" endpoint in v0.166.2 that the
    viewer role can call, so this function returns True for any already-created
    identity. Kept for backward compatibility with the Phase 4 caller.
    """
    # Identity creation already granted the role — nothing to do.
    return bool(mi_id)


def _revoke_machine_identity(mi_id: str) -> None:
    """Delete the machine identity (cascades: credentials + role grants)."""
    base = _infisical_url().rstrip("/")
    # v0.166.2: DELETE /api/v1/identities/{identityId}
    url = f"{base}/api/v1/identities/{mi_id}"
    resp = httpx.delete(url, headers=_admin_headers(), timeout=_API_TIMEOUT_S)
    # 404 on already-deleted is fine — operator-initiated revoke is
    # idempotent in spirit.
    if resp.status_code not in (200, 202, 204, 404):
        resp.raise_for_status()


def _audit_token(action: str, token_id: str, token_name: str) -> None:
    """Emit a streamlit_token_{action} event to Loki (NEVER token value).

    `action` is one of: 'create', 'rotate', 'revoke'. Failures are
    swallowed so a Loki outage never blocks the operator's UX.
    """
    try:
        from loki_logger import log_event
        log_event("streamlit", {
            "event": f"streamlit_token_{action}",
            "user_id": st.session_state.get("user_id"),
            "username": st.session_state.get("user"),
            "token_id": token_id,
            "token_name": token_name,
            # CRITICAL: never include the access token VALUE here.
        })
    except Exception:
        pass  # logging failures must never block a successful op


