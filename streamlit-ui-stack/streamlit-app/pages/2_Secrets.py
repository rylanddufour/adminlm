def _audit_view(secret_key: str, secret_path: str) -> None:
    """Emit a streamlit_secret_view event. NEVER includes the secret VALUE.

    Failures are swallowed so a Loki outage can never block the reveal
    UX (matches the auth.py + 1_Settings.py pattern).
    """
    try:
        from loki_logger import log_event
        log_event("streamlit", {
            "event": "streamlit_secret_view",
            "user_id": st.session_state.get("user_id"),
            "username": st.session_state.get("user"),
            "secret_key": secret_key,
            "secret_path": secret_path,
            # ts is added by log_event itself (RFC3339Nano); don't duplicate.
            # Verify the timestamp is what Loki sees, not the operator's
            # local clock, by leaving the field to the shipper.
        })
    except Exception:
        pass  # logging failures must never block a successful reveal


