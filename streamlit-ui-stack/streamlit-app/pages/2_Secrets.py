def _infisical_url() -> str:
    """Return the configured Infisical URL (override > env > default).

    Mirrors settings.py's _env_or pattern but inlined so this page works
    even when the operator's ui_settings table hasn't been initialised
    (the page can be the first Streamlit page loaded on a fresh install).
    """
    try:
        from db import get_ui_settings
        override = get_ui_settings().get("INFISICAL_URL", "").strip()
        if override:
            return override
    except Exception:
        pass
    return os.environ.get("INFISICAL_URL") or settings.infisical_url


def _operator_token() -> str:
    """Return the INFISICAL_OPERATOR_TOKEN env var, or '' if missing.

    bootstrap.sh deploy_infisical_stack() writes this to ~/.hermes/secrets/
    infisical-operator.env and docker-compose passes it into the container.
    If it's empty, we render the 'not initialised yet' hint instead of
    trying to call the API with an empty bearer (which 401s).
    """
    return os.environ.get("INFISICAL_OPERATOR_TOKEN", "").strip()


def _project_id() -> str:
    """Return the bootstrap-captured INFISICAL_PROJECT_ID, or '' if missing.

    The Infisical API needs workspaceId as a query param on every call;
    we resolve it from the operator env file at deploy time so the page
    doesn't have to enumerate projects on every request.
    """
    return os.environ.get("INFISICAL_PROJECT_ID", "").strip()


# ---------------------------------------------------------------------------
# API helpers — wrapped so render-time errors surface as friendly UI hints
# ---------------------------------------------------------------------------

def _list_secrets(path: str) -> list[dict]:
    """List secret METADATA under `path`. Never returns values.

    Endpoint: GET /api/v3/secrets?workspaceId=...&environment=...&secretPath=...&recursive=true
    Returns: list of {id, secretKey, secretPath, createdAt, updatedAt, version, ...}
    Raises httpx.HTTPError on transport failure (caught below).
    """
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    params = {
        "workspaceId": pid,
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path,
        # recursive=true: include secrets in nested folders under this path.
        # Phase 3 lists every secret under /adminlm/it-systems/<system>/ so
        # the operator sees them all without picking each system manually.
        # Phase 4 scope-policy will tighten this; for now the operator
        # token is scoped to /adminlm/* with read-only grants, so a
        # broader recursive listing can't leak out-of-scope data.
        "recursive": "true",
    }
    url = f"{base}/api/v3/secrets?{urlencode(params)}"
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    body = resp.json()
    # v3 returns {"secrets": [...]}; some versions return a bare list.
    if isinstance(body, dict):
        return body.get("secrets") or body.get("data") or []
    if isinstance(body, list):
        return body
    return []


def _list_subfolders(path: str) -> list[dict]:
    """List immediate subfolders of `path`. Used to populate the system filter.

    Endpoint: GET /api/v3/folders?workspaceId=...&environment=...&path=...
    Returns: list of {id, name, path, ...}
    """
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    params = {
        "workspaceId": pid,
        "environment": INFISICAL_ENV_SLUG,
        "path": path,
    }
    url = f"{base}/api/v3/folders?{urlencode(params)}"
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    body = resp.json()
    if isinstance(body, dict):
        return body.get("folders") or body.get("data") or []
    if isinstance(body, list):
        return body
    return []


def _read_secret(path: str, secret_key: str) -> dict:
    """Fetch a single secret including its VALUE for the reveal pane.

    Endpoint: GET /api/v3/secrets/raw?workspaceId=...&environment=...&secretPath=...&secretKey=...
    Returns: dict with at least {secretKey, secretValue, secretPath, ...}
    """
    base = _infisical_url().rstrip("/")
    pid = _project_id()
    params = {
        "workspaceId": pid,
        "environment": INFISICAL_ENV_SLUG,
        "secretPath": path,
        "secretKey": secret_key,
    }
    url = f"{base}/api/v3/secrets/raw?{urlencode(params)}"
    headers = {"Authorization": f"Bearer {_operator_token()}"}
    resp = httpx.get(url, headers=headers, timeout=_API_TIMEOUT_S)
    resp.raise_for_status()
    return resp.json()


# ---------------------------------------------------------------------------
# Audit helper — BACKLOG #77 loki_logger pattern
# ---------------------------------------------------------------------------

def _audit_view(secret_key: str, secret_path: str) -> None:
    """Emit a streamlit_secret_view event. NEVER includes the secret VALUE.

    Failures are swallowed so a Loki outage can never block the reveal
    UX (matches the auth.py + 1_Settings.py pattern).
    """
    try:
        from loki_logger import log_event
        log_event("streamlit", {
            "event": "streamlit_secret_view",
            "user_id": st.session_state.get("user_id"),
            "username": st.session_state.get("user"),
            "secret_key": secret_key,
            "secret_path": secret_path,
            # ts is added by log_event itself (RFC3339Nano); don't duplicate.
            # Verify the timestamp is what Loki sees, not the operator's
            # local clock, by leaving the field to the shipper.
        })
    except Exception:
        pass  # logging failures must never block a successful reveal


